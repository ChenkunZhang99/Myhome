/**
 * 按数量给出正确的单位写法。
 * kg、ml 这类计量单位本来就是拉丁字母，不在字典里，会原样返回且不加复数。
 */
export function translateUnit(locale: Locale, unit: string, quantity = 1) {
  if (locale === "zh" || !unit) return unit;
  if (Math.abs(quantity) === 1) return values[unit] ?? unit;
  return unitPlurals[unit] ?? values[unit] ?? unit;
}

/** 数字按语言习惯格式化。 */
export function formatNumber(locale: Locale, value: number) {
  return new Intl.NumberFormat(locale === "zh" ? "zh-CN" : "en-CA", { maximumFractionDigits: 2 }).format(
    value,
  );
}

/** 日期按语言习惯显示：中文「2026年08月16日」，英文「Aug 16, 2026」。 */
export function formatDate(locale: Locale, date?: string | null) {
  if (!date) return "";
  const [year, month, day] = date.split("-");
  if (locale === "zh") return `${year}年${month}月${day}日`;
  const parsed = new Date(`${date}T00:00:00`);
  if (Number.isNaN(parsed.getTime())) return date;
  return new Intl.DateTimeFormat("en-CA", { year: "numeric", month: "short", day: "numeric" }).format(parsed);
}

/**
 * 时刻（不只是日期）。formatDate 只吃 YYYY-MM-DD，喂它完整时间戳会得到
 * 「2026年08月22T16:29:59.125Z日」这种东西。
 *
 * 这里用设备本地时区，不用家庭时区——保质期倒计时那类「对这个家有意义的日期」
 * 才跟着家走；备份是系统事件，看的人关心的是「相对我现在是什么时候」。
 */
export function formatDateTime(locale: Locale, iso?: string | null) {
  if (!iso) return "";
  const parsed = new Date(iso);
  if (Number.isNaN(parsed.getTime())) return iso;
  return new Intl.DateTimeFormat(locale === "zh" ? "zh-CN" : "en-CA", {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(parsed);
}

export const defaultLocale: Locale = "zh";

export function isLocale(value: unknown): value is Locale {
  return value === "zh" || value === "en";
}
