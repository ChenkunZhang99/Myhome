const dictionaries: Record<Locale, Record<string, string>> = {
  zh: {},
  en: { ...values, ...ui },
};

function interpolate(text: string, vars?: Record<string, string | number>) {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

/** 翻译一段界面文案；查不到就原样返回中文。 */
export function translate(locale: Locale, text: string, vars?: Record<string, string | number>) {
  const entry = dictionaries[locale]?.[text];
  return interpolate(entry ?? text, vars);
}

/**
 * 翻译一个存储值（分类、单位、库存等级……）。
 * 只影响显示，写回数据库的永远是传进来的中文原值。
 */
export function translateValue(locale: Locale, value: string | null | undefined) {
  if (!value) return "";
  if (locale === "zh") return value;
  return values[value] ?? value;
}

